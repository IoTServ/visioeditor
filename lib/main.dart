  /// True when a text field / inline editor owns primary focus so plain keys
  /// (Delete, arrows, …) must not mutate the diagram.
  bool _isEditableTextFocused() {
    final primary = FocusManager.instance.primaryFocus;
    final ctx = primary?.context;
    if (ctx == null) return false;
    return ctx.findAncestorStateOfType<EditableTextState>() != null;
  }

  /// Editor shortcuts with both Cmd (macOS) and Ctrl (Windows/Linux) bindings.
  ///
  /// Plain keys such as Delete / arrows are bound here (not only on the canvas
  /// [Focus]) so they still work after focus moves to a toolbar button or
  /// sidebar control. Editable text focus is excluded via
  /// [EditorCallbackShortcuts] (must not consume the key — a no-op callback
  /// on [CallbackShortcuts] still blocks default text-editing shortcuts).
  Map<ShortcutActivator, VoidCallback> _editorShortcutBindings(
    EditorController? Function() c,
  ) {
    final bindings = <ShortcutActivator, VoidCallback>{};

    void mod(
      LogicalKeyboardKey key,
      VoidCallback action, {
      bool shift = false,
      bool alt = false,
    }) {
      bindings[SingleActivator(key, meta: true, shift: shift, alt: alt)] =
          action;
      bindings[SingleActivator(key, control: true, shift: shift, alt: alt)] =
          action;
    }

    void redo() {
      final cur = c();
      if (cur != null && cur.canRedo) cur.redo();
    }

    // Delete / Backspace: remove selection (or a connection point while editing
    // glue). Bound at app level so they work even when the canvas Focus node
    // does not have primary focus (e.g. after clicking a toolstrip button).
    void deleteSel({bool includeConnected = false}) {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur == null || !cur.hasDocument) return;
      if (cur.editingConnectionPoints) {
        cur.deleteSelection();
        return;
      }
      if (cur.hasSelection) {
        cur.deleteSelection(includeConnected: includeConnected);
      }
    }

    bindings[const SingleActivator(LogicalKeyboardKey.delete)] = deleteSel;
    bindings[const SingleActivator(LogicalKeyboardKey.backspace)] = deleteSel;
    mod(
      LogicalKeyboardKey.delete,
      () => deleteSel(includeConnected: true),
    );
    mod(
      LogicalKeyboardKey.backspace,
      () => deleteSel(includeConnected: true),
    );
    void clearLabels() {
      if (_presentationMode || _isEditableTextFocused()) return;
      c()?.clearSelectionLabels();
    }
    bindings[const SingleActivator(
      LogicalKeyboardKey.delete,
      shift: true,
    )] = clearLabels;
    bindings[const SingleActivator(
      LogicalKeyboardKey.backspace,
      shift: true,
    )] = clearLabels;

    // draw.io: Enter edits the selected label, or toggles reset/fit when there
    // is no selection. Cmd/Ctrl+Enter duplicates the selection; table cells are
    // promoted to their containing row.
    bindings[const SingleActivator(LogicalKeyboardKey.enter)] = () {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur == null || !cur.hasDocument) return;
      if (cur.hasSelection) {
        cur.requestEditSelectionLabel();
      } else {
        cur.requestSmartFit();
      }
    };
    bindings[const SingleActivator(LogicalKeyboardKey.f2)] = () {
      if (_presentationMode || _isEditableTextFocused()) return;
      c()?.requestEditSelectionLabel();
    };
    mod(LogicalKeyboardKey.enter, () {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur != null && cur.canDuplicateSelectionFromEnter) {
        cur.duplicateSelectionFromEnter();
      }
    });

    // draw.io: Cmd/Ctrl+Shift+NumPad +/- and Cmd/Ctrl+{/} change the entire
    // selected label by one point, even when only part of the inline label is
    // selected.
    void adjustWholeLabelTextSize(double deltaPoints) {
      if (_presentationMode) return;
      final cur = c();
      if (cur == null || !cur.hasSelection) return;
      // Keep the shortcut available in the canvas inline editor, but never
      // steal it from search fields, settings fields, or other text inputs.
      if (_isEditableTextFocused() && cur.textEditShapeId == null) return;
      cur.adjustWholeLabelTextSizePoints(deltaPoints);
    }

    mod(
      LogicalKeyboardKey.numpadAdd,
      () => adjustWholeLabelTextSize(1),
      shift: true,
    );
    mod(
      LogicalKeyboardKey.numpadSubtract,
      () => adjustWholeLabelTextSize(-1),
      shift: true,
    );
    mod(
      LogicalKeyboardKey.bracketRight,
      () => adjustWholeLabelTextSize(1),
      shift: true,
    );
    mod(
      LogicalKeyboardKey.bracketLeft,
      () => adjustWholeLabelTextSize(-1),
      shift: true,
    );

    // Arrow-key nudge (same step as the canvas handler).
    void nudge(double dx, double dy) {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur == null ||
          !cur.hasSelection ||
          cur.editingConnectionPoints) {
        return;
      }
      final step = cur.snapToGrid ? cur.gridInches : 0.1;
      cur.moveSelectionBy(dx * step, dy * step);
    }

    void nudgeOrMovePage(double dx, double dy) {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur == null || !cur.hasDocument) return;
      if (cur.hasSelection) {
        nudge(dx, dy);
      } else if (dx < 0) {
        cur.moveCurrentPageBy(-1);
      } else if (dx > 0) {
        cur.moveCurrentPageBy(1);
      } else if (dy > 0) {
        cur.moveCurrentPageToBoundary(last: false);
      } else if (dy < 0) {
        cur.moveCurrentPageToBoundary(last: true);
      }
    }

    bindings[const SingleActivator(LogicalKeyboardKey.arrowLeft)] =
        () => nudge(-1, 0);
    bindings[const SingleActivator(LogicalKeyboardKey.arrowRight)] =
        () => nudge(1, 0);
    bindings[const SingleActivator(LogicalKeyboardKey.arrowUp)] =
        () => nudge(0, 1);
    bindings[const SingleActivator(LogicalKeyboardKey.arrowDown)] =
        () => nudge(0, -1);
    bindings[const SingleActivator(
      LogicalKeyboardKey.arrowLeft,
      shift: true,
    )] = () => nudgeOrMovePage(-1, 0);
    bindings[const SingleActivator(
      LogicalKeyboardKey.arrowRight,
      shift: true,
    )] = () => nudgeOrMovePage(1, 0);
    bindings[const SingleActivator(
      LogicalKeyboardKey.arrowUp,
      shift: true,
    )] = () => nudgeOrMovePage(0, 1);
    bindings[const SingleActivator(
      LogicalKeyboardKey.arrowDown,
      shift: true,
    )] = () => nudgeOrMovePage(0, -1);

    // draw.io: Cmd/Ctrl+Shift+arrow adjusts the selected shape's right or
    // lower edge by one grid step (Arrange-panel Width / Height).
    void resizeSelection(double dw, double dh, {bool byPoint = false}) {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      final geometry = cur?.selectedGeometry;
      if (cur == null ||
          geometry == null ||
          cur.singleSelected?.is1D == true ||
          cur.editingConnectionPoints) {
        return;
      }
      final step =
          byPoint ? 1 / 72 : (cur.snapToGrid ? cur.gridInches : 0.1);
      if (dw != 0) cur.setSelectedWidth(geometry.w + dw * step);
      if (dh != 0) cur.setSelectedHeight(geometry.h + dh * step);
    }

    // Without a shape selection the same Ctrl/Cmd+Arrow chords navigate page
    // tabs. With a selection draw.io resizes the right/lower edge by 1pt.
    void resizeOrSelectPage(double dw, double dh) {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur == null || !cur.hasDocument) return;
      if (cur.hasSelection) {
        resizeSelection(dw, dh, byPoint: true);
      } else if (dw < 0) {
        cur.selectRelativePage(-1);
      } else if (dw > 0) {
        cur.selectRelativePage(1);
      } else if (dh < 0) {
        cur.selectBoundaryPage(last: false);
      } else if (dh > 0) {
        cur.selectBoundaryPage(last: true);
      }
    }

    mod(LogicalKeyboardKey.arrowLeft, () => resizeOrSelectPage(-1, 0));
    mod(LogicalKeyboardKey.arrowRight, () => resizeOrSelectPage(1, 0));
    mod(LogicalKeyboardKey.arrowUp, () => resizeOrSelectPage(0, -1));
    mod(LogicalKeyboardKey.arrowDown, () => resizeOrSelectPage(0, 1));
    mod(LogicalKeyboardKey.arrowLeft, () => resizeSelection(-1, 0),
        shift: true);
    mod(LogicalKeyboardKey.arrowRight, () => resizeSelection(1, 0),
        shift: true);
    mod(LogicalKeyboardKey.arrowUp, () => resizeSelection(0, -1),
        shift: true);
    mod(LogicalKeyboardKey.arrowDown, () => resizeSelection(0, 1),
        shift: true);
    mod(LogicalKeyboardKey.pageUp, () => c()?.selectRelativePage(-1),
        shift: true);
    mod(LogicalKeyboardKey.pageDown, () => c()?.selectRelativePage(1),
        shift: true);

    mod(LogicalKeyboardKey.keyN, _newDoc);
    mod(LogicalKeyboardKey.keyO, _open);
    mod(LogicalKeyboardKey.keyW, () {
      if (_workspace.hasDocs) _closeTab(_workspace.activeIndex);
    });
    mod(LogicalKeyboardKey.keyS, () {
      if (c() != null && c()!.hasDocument) _save();
    });
    mod(LogicalKeyboardKey.keyS, () {
      if (c() != null && c()!.hasDocument) _saveAs();
    }, shift: true);
    mod(LogicalKeyboardKey.keyZ, () {
      final cur = c();
      if (cur != null && cur.canUndo) cur.undo();
    });
    mod(LogicalKeyboardKey.keyZ, redo, shift: true);
    // Windows/Linux redo convention; also bind meta+Y for completeness.
    bindings[const SingleActivator(LogicalKeyboardKey.keyY, control: true)] =
        redo;
    bindings[const SingleActivator(LogicalKeyboardKey.keyY, meta: true)] = redo;
    // draw.io Arrange → Autosize.
    mod(LogicalKeyboardKey.keyY, () {
      if (_presentationMode || _isEditableTextFocused()) return;
      final cur = c();
      if (cur != null && cur.canAutosizeSelection) {
        cur.autosizeSelection();
      }
    }, shift: true);
    mod(LogicalKeyboardKey.keyD, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.duplicateSelection();
    });
    mod(LogicalKeyboardKey.keyD, () {
      final cur = c();
      if (cur != null && cur.hasSelection) {
        cur.setSelectionAsDefaultStyle();
      }
    }, shift: true);
    mod(LogicalKeyboardKey.keyC, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.copySelection();
    });
    mod(LogicalKeyboardKey.keyV, () {
      final cur = c();
      if (cur != null && cur.hasDocument) {
        // Always try the system clipboard first (cross-instance paste).
        unawaited(cur.pasteFromSystem());
      }
    });
    mod(LogicalKeyboardKey.keyX, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.cut();
    });
    mod(LogicalKeyboardKey.keyA, () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectAll();
    });
    mod(LogicalKeyboardKey.keyA, () {
      final cur = c();
      if (cur != null) cur.clearSelection();
    }, shift: true);
    mod(LogicalKeyboardKey.keyB, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleBold();
    });
    mod(LogicalKeyboardKey.keyI, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleItalic();
    });
    mod(LogicalKeyboardKey.keyU, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleUnderline();
    });
    mod(LogicalKeyboardKey.keyE, () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectConnectors();
    }, shift: true);
    mod(LogicalKeyboardKey.keyI, () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectVertices();
    }, shift: true);
    bindings[const SingleActivator(LogicalKeyboardKey.tab)] = () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectNextShape();
    };
    bindings[const SingleActivator(LogicalKeyboardKey.tab, shift: true)] = () {
      final cur = c();
      if (cur != null && cur.hasDocument) {
        cur.selectNextShape(reverse: true);
      }
    };
    bindings[const SingleActivator(LogicalKeyboardKey.tab, alt: true)] = () {
      if (_presentationMode || _isEditableTextFocused()) return;
      c()?.selectParentShape();
    };
    // draw.io view shortcuts: Home resets to 100%; Cmd/Ctrl+J and
    // Cmd/Ctrl+Shift+H fit one page.
    bindings[const SingleActivator(LogicalKeyboardKey.home)] = () {
      if (_presentationMode || _isEditableTextFocused()) return;
      c()?.requestResetView();
    };
    mod(LogicalKeyboardKey.keyJ, () {
      if (_presentationMode || _isEditableTextFocused()) return;
      c()?.requestFitToWindow();
    });
    mod(LogicalKeyboardKey.keyH, () {
      if (_presentationMode || _isEditableTextFocused()) return;
      c()?.requestFitToWindow();
    }, shift: true);
    void requestView(VoidCallback action) {
      if (_presentationMode || _isEditableTextFocused()) return;
      action();
    }
    mod(
      LogicalKeyboardKey.digit0,
      () => requestView(() => c()?.requestCustomZoom()),
