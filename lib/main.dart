  Widget _arrowSizeRow(double inches, ValueChanged<double> onChanged) {
    final buckets = EditorController.arrowSizeBuckets;
    var selected = 2;
    var best = double.infinity;
    for (var i = 0; i < buckets.length; i++) {
      final d = (buckets[i] - inches).abs();
      if (d < best) {
        best = d;
        selected = i;
