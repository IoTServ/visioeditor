      spacing: 4,
      children: [
        for (var i = 0; i < buckets.length; i++)
          ChoiceChip(
            label: Text('${i + 1}', style: const TextStyle(fontSize: 11)),
            selected: selected == i,
            onSelected: (_) => onChanged(buckets[i]),
            visualDensity: VisualDensity.compact,
            materialTapTargetSize: MaterialTapTargetSize.shrinkWrap,
