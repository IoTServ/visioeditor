/// A single open-file tab in the top tab bar.
///
/// Drag-to-reorder is limited to the label area (not the close / menu buttons).
/// Right-click the label or tap ⋮ for close-related actions.
class _DocTab extends StatelessWidget {
  const _DocTab({
    super.key,
    required this.index,
    required this.label,
    required this.dirty,
    required this.active,
    required this.onTap,
    required this.onClose,
    required this.onMenu,
  });

  final int index;
  final String label;
  final bool dirty;
  final bool active;
  final VoidCallback onTap;
  final VoidCallback onClose;
  final void Function(Offset globalPosition) onMenu;

  void _menuAt(BuildContext context, {Alignment alignment = Alignment.bottomCenter}) {
    final box = context.findRenderObject() as RenderBox?;
    if (box == null || !box.hasSize) {
      onMenu(Offset.zero);
      return;
    }
    final origin = box.localToGlobal(Offset.zero);
    final size = box.size;
    onMenu(Offset(
      origin.dx + size.width * (alignment.x + 1) / 2,
      origin.dy + size.height * (alignment.y + 1) / 2,
    ));
  }

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final el = EditorL10n.of(context);
    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 2, vertical: 4),
      child: Material(
        color: active ? scheme.surface : Colors.transparent,
        borderRadius: BorderRadius.circular(8),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: [
            // Only the title chip is a reorder handle — chrome stays clickable.
            ReorderableDragStartListener(
              index: index,
              child: Tooltip(
                message: el.tabReorderHint,
                waitDuration: const Duration(milliseconds: 600),
                child: InkWell(
                  onTap: onTap,
                  onSecondaryTapDown: (d) => onMenu(d.globalPosition),
                  borderRadius: const BorderRadius.horizontal(
                    left: Radius.circular(8),
                  ),
                  child: Padding(
                    padding: const EdgeInsets.only(left: 12, right: 2),
                    child: Row(
                      mainAxisSize: MainAxisSize.min,
                      children: [
                        if (dirty)
                          Padding(
                            padding: const EdgeInsets.only(right: 6),
                            child: Icon(
                              Icons.circle,
                              size: 8,
                              color: scheme.primary,
                            ),
                          ),
                        ConstrainedBox(
                          constraints: const BoxConstraints(maxWidth: 148),
                          child: Text(
                            label,
                            overflow: TextOverflow.ellipsis,
                            style: TextStyle(
                              fontWeight:
                                  active ? FontWeight.w600 : FontWeight.w400,
                            ),
                          ),
                        ),
                      ],
                    ),
                  ),
                ),
              ),
            ),
            IconButton(
              onPressed: () =>
                  _menuAt(context, alignment: Alignment.bottomRight),
              icon: const Icon(Icons.arrow_drop_down, size: 18),
              visualDensity: VisualDensity.compact,
              padding: EdgeInsets.zero,
              constraints: const BoxConstraints(minWidth: 28, minHeight: 32),
              tooltip: el.tabMenuTooltip,
            ),
            IconButton(
              onPressed: onClose,
              icon: const Icon(Icons.close, size: 16),
              visualDensity: VisualDensity.compact,
              padding: EdgeInsets.zero,
              constraints: const BoxConstraints(minWidth: 28, minHeight: 32),
              tooltip: el.closeTab,
            ),
          ],
        ),
      ),
    );
  }
}

/// Friendly chip labels for starter templates (zh when locale is Chinese).
String _exampleLabel(BuildContext context, String assetName) {
  final zh = Localizations.localeOf(context).languageCode == 'zh';
  for (final t in kDiagramTemplates) {
    if (t.assetName == assetName) {
      return zh ? t.titleZh : t.titleEn;
    }
  }
  return assetName.replaceAll('.vsdx', '');
}

