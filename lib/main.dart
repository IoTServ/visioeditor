  /// few built-in demos. Prefer the templates for new drawings.
  static const List<String> _examples = <String>[
    'Process Flow.vsdx',
    'Org Chart.vsdx',
    'Project Roadmap.vsdx',
    'SWOT Matrix.vsdx',
    'System Architecture.vsdx',
    'workflow.vsdx',
