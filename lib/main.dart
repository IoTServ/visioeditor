  void _onPageTabSelected(int index) {
    final c = _c;
    if (c == null) return;
    final now = DateTime.now();
    final isDoubleTap = _lastPageTabIndex == index &&
        _lastPageTabTapAt != null &&
        now.difference(_lastPageTabTapAt!) < const Duration(milliseconds: 400);
    _lastPageTabIndex = index;
    _lastPageTabTapAt = now;
    if (isDoubleTap) {
      _lastPageTabTapAt = null;
      _renamePage(index);
      return;
    }
    c.selectPage(index);
  }

  Future<void> _renamePage(int index) async {
    final c = _c;
    final doc = c?.document;
    if (c == null || doc == null || index < 0 || index >= doc.pages.length) {
      return;
    }
    final textController =
        TextEditingController(text: doc.pages[index].name);
    final el = EditorL10n.of(context);
    final result = await showDialog<String>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text(el.renamePage),
        content: TextField(
          controller: textController,
          autofocus: true,
          decoration: InputDecoration(hintText: el.pageNameHint),
          onSubmitted: (v) => Navigator.pop(ctx, v),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: Text(el.cancel),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(ctx, textController.text),
            child: Text(el.ok),
          ),
        ],
      ),
    );
    if (result != null) c.renamePageAt(index, result);
    textController.dispose();
  }

