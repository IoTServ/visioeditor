      final cur = c();
      if (cur != null && cur.hasSelection) cur.bringSelectionToFront();
    }, shift: true);
    mod(LogicalKeyboardKey.keyB, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.sendSelectionToBack();
