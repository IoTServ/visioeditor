  }

  /// Open drawio's "Edit Link" (Cmd+K) for the single selected shape.
  Future<void> _editLink() async {
    final c = _c;
    final id = c?.singleSelectedId;
    if (c == null || id == null) return;
    await showEditLinkDialog(context, c, id);
  }

  @override
  void initState() {
    super.initState();
    // Document edits are observed via [ListenableBuilder] below — do not
    // setState the whole Scaffold on every controller tick (that rebuilt the
    // shapes palette's ~300 thumbnails and made scrollbars/sliders lag).
    _recentFiles.load().then((r) {
      if (mounted) setState(() => _recents = r);
    });
    if (!kIsWeb &&
        (defaultTargetPlatform == TargetPlatform.macOS ||
            defaultTargetPlatform == TargetPlatform.iOS)) {
      _fileChannel.setMethodCallHandler(_onNativeMethod);
      // Tell the native side we're listening so it can flush any file that was
      // opened before the Dart isolate was ready (cold launch from Finder /
      // Files / "Open in…").
      unawaited(_fileChannel.invokeMethod<void>('ready').catchError((Object _) {}));
    }
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    // Wide: open the shapes sidebar so the responsive group seeds inside
    // [_StencilPanel] are visible. Narrow: keep it closed to preserve canvas.
    // Assignment without setState is fine — MediaQuery already schedules build.
    if (!_stencilsUserAdjusted) {
      _showStencils =
          MediaQuery.sizeOf(context).width >= _stencilsSidebarBreakpoint;
    }
  }

  void _closeLibrarySidebars({bool keepStencils = false}) {
    if (!keepStencils) _showStencils = false;
    _showImageMaterials = false;
    _showThirdPartyIcons = false;
  }

  void _toggleStencils() {
    setState(() {
      _stencilsUserAdjusted = true;
      final open = !_showStencils;
      _closeLibrarySidebars(keepStencils: true);
      _showStencils = open;
    });
  }

  void _toggleImageMaterials() {
    setState(() {
      final open = !_showImageMaterials;
      _closeLibrarySidebars();
      if (open) {
        _stencilsUserAdjusted = true;
        _showImageMaterials = true;
      }
    });
  }

  void _toggleThirdPartyIcons() {
    setState(() {
      final open = !_showThirdPartyIcons;
      _closeLibrarySidebars();
      if (open) {
        _stencilsUserAdjusted = true;
        _showThirdPartyIcons = true;
      }
    });
  }

  /// Insert a built-in clipart asset as a picture shape (capped size).
  Future<void> _insertImageMaterial(
    ImageMaterial material, {
    Offset? pagePt,
  }) async {
    final c = _c;
    if (c == null || !c.hasDocument) return;
    try {
      final data = await rootBundle.load(material.assetPath);
      final bytes = data.buffer.asUint8List();
      if (bytes.isEmpty) return;
      var size = await _imageSizeInches(bytes);
      size = _clampImageMaterialSize(size.$1, size.$2);
      if (!mounted) return;
      c.insertImage(
        bytes,
        fileExtension: material.fileExtension,
        widthInches: size.$1,
        heightInches: size.$2,
        cx: pagePt?.dx,
        cy: pagePt?.dy,
      );
      _snack(EditorL10n.of(context).insertedNamed(
        EditorL10n.of(context).imageMaterial(material.name),
      ));
    } catch (_) {
      if (mounted) {
        _snack(EditorL10n.of(context).insertImageFailed);
      }
    }
  }

  /// Keep material inserts small even if a future asset is larger than 64×64.
  (double, double) _clampImageMaterialSize(double? w, double? h) {
    var width = w ?? kImageMaterialMaxInches;
    var height = h ?? kImageMaterialMaxInches;
    if (width <= 0) width = kImageMaterialMaxInches;
    if (height <= 0) height = kImageMaterialMaxInches;
    final maxEdge = math.max(width, height);
    if (maxEdge > kImageMaterialMaxInches) {
      final s = kImageMaterialMaxInches / maxEdge;
      width *= s;
      height *= s;
    }
    return (width, height);
  }

  /// Rasterise a third-party [IconData] and insert it as a picture shape.
  Future<void> _insertThirdPartyIcon(
    ThirdPartyIcon entry, {
    Offset? pagePt,
  }) async {
    final c = _c;
    if (c == null || !c.hasDocument) return;
    try {
      final bytes = await rasterizeThirdPartyIcon(entry.icon);
      if (bytes.isEmpty || !mounted) return;
      c.insertImage(
        bytes,
        fileExtension: 'png',
        widthInches: kThirdPartyIconMaxInches,
        heightInches: kThirdPartyIconMaxInches,
        cx: pagePt?.dx,
        cy: pagePt?.dy,
      );
      _snack(EditorL10n.of(context).insertedNamed(entry.name));
    } catch (_) {
      if (mounted) {
        _snack(EditorL10n.of(context).insertImageFailed);
      }
    }
  }

  /// Handle calls pushed from the native side (currently only `openFiles`).
  Future<dynamic> _onNativeMethod(MethodCall call) async {
    if (call.method == 'openFiles') {
      final args = call.arguments;
      if (args is List) {
        for (final p in args) {
          if (p is String && hasVisioAssociatedExtension(p)) {
            await _openPath(p);
          }
        }
      }
    }
    return null;
  }

  @override
  void dispose() {
    if (_presentationMode) _applyPresentationSystemUi(false);
    _agentBridge?.dispose();
    _workspace.dispose();
    _camera.dispose();
    super.dispose();
  }

  /// Start/stop the loopback live-preview bridge (see `AgentBridge`).
  Future<void> _toggleAgentPreview() async {
    final bridge = _agentBridge;
    if (bridge != null) {
      await bridge.stop();
      bridge.dispose();
      if (mounted) setState(() => _agentBridge = null);
      _snack('Agent live preview off');
      return;
    }
    try {
      final b = AgentBridge(workspace: _workspace, openPath: _openPath);
      await b.start();
      if (mounted) setState(() => _agentBridge = b);
      _snack('Agent live preview on · 127.0.0.1:${b.port}');
    } catch (e) {
      _snack('Agent live preview failed: $e');
    }
  }

  Future<void> _addRecent(String? path) async {
    if (path == null) return;
    final r = await _recentFiles.add(path);
    if (mounted) setState(() => _recents = r);
  }

  /// Open bytes in a NEW tab; drops the tab and reports if parsing failed.
  Future<void> _openBytes(
    Uint8List bytes, {
    String? path,
    String? name,
  }) async {
    final c = await _workspace.openBytes(bytes, path: path, name: name);
    if (c.error != null) {
      if (mounted) {
        _snack(EditorL10n.of(context).openFileFailed('${c.error}'));
      }
      final i = _workspace.indexOf(c);
      if (i >= 0) _workspace.closeAt(i);
      return;
    }
    if (mounted && c.importedFromVsd) {
      _snack(EditorL10n.of(context).vsdImportedSaveAsVsdx);
    }
    if (path != null) await _addRecent(path);
  }

  Future<void> _open() async {
    final picked = await pickVisioFile();
    if (picked == null) return;
    await _openBytes(picked.bytes, path: picked.path, name: picked.name);
  }

  Future<void> _openPath(String path) async {
    try {
      final picked = await readDroppedFile(path);
      await _openBytes(picked.bytes, path: picked.path, name: picked.name);
    } catch (e) {
      if (mounted) {
        _snack(EditorL10n.of(context).openPathFailed(path));
      }
    }
  }

  Future<void> _openExample(String assetName) async {
    try {
      final data = await rootBundle.load('assets/examples/$assetName');
      await _openBytes(data.buffer.asUint8List(), name: assetName);
    } catch (e) {
      if (mounted) {
        _snack(EditorL10n.of(context).openExampleFailed(assetName));
      }
    }
  }

  Future<void> _onDrop(DropDoneDetails details) async {
    setState(() => _dragging = false);
    final c = _c;
    final pagePt = _pageInchesFromGlobal(details.globalPosition);
    for (final f in details.files) {
      if (hasVisioExtension(f.path) || isLegacyVisioBinary(f.path)) {
        final picked = await readDroppedFile(f.path);
        await _openBytes(picked.bytes, path: picked.path, name: picked.name);
        continue;
      }
      // Raster image → insert at the drop point (or replace a picture under
      // the cursor), matching drawio's drag-from-desktop behaviour.
      if (c != null && c.hasDocument && hasImageExtension(f.path)) {
        try {
          final bytes = await f.readAsBytes();
          await _embedImageBytes(
            c,
            bytes,
            fileExtension: extensionOfPath(f.path),
            name: f.name,
            pagePt: pagePt,
          );
        } catch (_) {
          if (mounted) {
            _snack(EditorL10n.of(context).insertImageFailed);
          }
        }
      }
    }
  }

  /// Map a screen position onto the active page (inches), or `null` when the
  /// canvas hasn't laid out / the point is outside the host.
  Offset? _pageInchesFromGlobal(Offset global) {
    final box =
        _canvasHostKey.currentContext?.findRenderObject() as RenderBox?;
    final page = _c?.currentPage;
    if (box == null || !box.hasSize || page == null) return null;
    final local = box.globalToLocal(global);
    final cam = _camera;
    if (cam.scale <= 0) return null;
    final content = (local - cam.offset) / cam.scale;
    const ppi = 96.0;
    return Offset(
      content.dx / ppi,
      page.heightInches - content.dy / ppi,
    );
  }

  /// Insert or replace a picture from [bytes] at optional [pagePt].
  Future<void> _embedImageBytes(
    EditorController c,
    Uint8List bytes, {
    required String fileExtension,
    String? name,
    Offset? pagePt,
    bool replaceSelected = false,
  }) async {
    if (bytes.isEmpty) return;
    final size = await _imageSizeInches(bytes);
    if (!mounted) return;
    final label = name ?? 'image';
    final el = EditorL10n.of(context);
    if (replaceSelected && c.canReplaceSelectedImage) {
      c.replaceImage(
        c.singleSelectedId!,
        bytes,
        fileExtension: fileExtension,
      );
      _snack(el.replacedWith(label));
      return;
    }
    // Drop onto an existing picture → replace its media (drawio).
    if (pagePt != null) {
      final hit = c.pictureShapeAt(pagePt.dx, pagePt.dy);
      if (hit != null) {
        c.replaceImage(hit, bytes, fileExtension: fileExtension);
        _snack(el.replacedWith(label));
        return;
      }
    }
    c.insertImage(
      bytes,
      fileExtension: fileExtension,
      widthInches: size.$1,
      heightInches: size.$2,
      cx: pagePt?.dx,
      cy: pagePt?.dy,
    );
    _snack(el.insertedNamed(label));
  }

  /// Pixel size → inches at 96 dpi; `(null, null)` when undecodable.
  Future<(double?, double?)> _imageSizeInches(Uint8List bytes) async {
    try {
      final codec = await ui.instantiateImageCodec(bytes);
      final frame = await codec.getNextFrame();
      final w = frame.image.width / 96.0;
      final h = frame.image.height / 96.0;
      frame.image.dispose();
      return (w, h);
    } catch (_) {
      return (null, null);
    }
  }

  Future<bool> _confirmDiscard(EditorController c) async {
    if (!c.isDirty) return true;
    final el = EditorL10n.of(context);
    final ok = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text(el.discardUnsavedTitle),
        content: Text(el.discardUnsavedBody(c.fileName ?? el.untitled)),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            child: Text(el.cancel),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(ctx, true),
            child: Text(el.discard),
          ),
        ],
      ),
    );
    return ok ?? false;
  }

  void _newDoc() => _workspace.newDocument();

  Future<void> _closeTab(int index) async {
    if (index < 0 || index >= _workspace.docs.length) return;
    if (await _confirmDiscard(_workspace.docs[index])) {
      _workspace.closeAt(index);
    }
  }

  Future<void> _save() async {
    final c = _c;
    if (c == null || !c.hasDocument) return;
    final el = EditorL10n.of(context);
    var path = c.filePath;
    // Never overwrite a legacy .vsd with OPC bytes.
    if (path != null && isLegacyVisioBinary(path)) {
      path = null;
    }
    path ??=
        await pickSaveLocation(suggestedName: c.fileName ?? 'drawing.vsdx');
    if (path == null) return;
    try {
      final bytes = c.exportToBytes();
      await writeBytesToFile(path, bytes);
      c.markSaved(bytes, path: path);
      await _addRecent(path);
      if (!mounted) return;
      _snack(el.savedTo(path));
    } catch (e) {
      if (!mounted) return;
      _snack(el.saveFailed('$e'));
    }
  }

  Future<void> _saveAs() async {
    final c = _c;
    if (c == null || !c.hasDocument) return;
    final el = EditorL10n.of(context);
    final path =
        await pickSaveLocation(suggestedName: c.fileName ?? 'drawing.vsdx');
    if (path == null) return;
    try {
      final bytes = c.exportToBytes();
      await writeBytesToFile(path, bytes);
      c.markSaved(bytes, path: path);
      await _addRecent(path);
      if (!mounted) return;
      _snack(el.savedTo(path));
    } catch (e) {
      if (!mounted) return;
      _snack(el.saveFailed('$e'));
    }
  }

  Future<void> _exportSvg() async {
    final c = _c;
    final doc = c?.document;
    if (c == null || doc == null) return;
    final el = EditorL10n.of(context);
    final path = await pickExportLocation(
      ext: 'svg',
      suggestedName: '${baseName(c.fileName)}.svg',
    );
    if (path == null) return;
    try {
      final svg = VsdxToSvgSerializer(
        layerFilter: SvgLayerFilter.print,
      ).serializeDocument(doc);
      await writeBytesToFile(path, Uint8List.fromList(utf8.encode(svg)));
      if (!mounted) return;
      _snack(el.exportedSvg(path));
    } catch (e) {
      if (!mounted) return;
      _snack(el.svgExportFailed('$e'));
    }
  }

  Future<void> _exportPng() async {
    final c = _c;
    final doc = c?.document;
    final page = c?.currentPage;
    if (c == null || doc == null || page == null) return;
    final el = EditorL10n.of(context);
    final path = await pickExportLocation(
      ext: 'png',
      suggestedName: '${baseName(c.fileName)}.png',
    );
    if (path == null) return;
    try {
      final bytes = await renderPageToPng(
        page,
        theme: doc.theme,
        images: doc.images,
        underlayPage: doc.backgroundFor(page),
      );
      if (bytes == null) {
        if (!mounted) return;
        _snack(el.pngExportFailed);
        return;
      }
      await writeBytesToFile(path, bytes);
      if (!mounted) return;
      _snack(el.exportedPng(path));
    } catch (e) {
      if (!mounted) return;
      _snack(el.pngExportFailedError('$e'));
    }
  }

  /// Insert an embedded raster image (drawio's "Insert > Image"): pick a file,
  /// size the placement box from the image's pixel dimensions (96 dpi), and
  /// hand the bytes to the controller, which embeds and round-trips them.
  /// When [replaceSelected] is true and a picture is selected, replaces it.
  Future<void> _insertImage({bool replaceSelected = false}) async {
    final c = _c;
    if (c == null || !c.hasDocument) return;
    final PickedImage? picked = await pickImageFile();
    if (picked == null) return;
    await _embedImageBytes(
      c,
      picked.bytes,
      fileExtension: picked.extension,
      name: picked.name,
      replaceSelected: replaceSelected,
    );
  }

  void _onPageTabSelected(int index) {
    final c = _c;
    if (c == null) return;
    final now = DateTime.now();
    final isDoubleTap = _lastPageTabIndex == index &&
        _lastPageTabTapAt != null &&
        now.difference(_lastPageTabTapAt!) < const Duration(milliseconds: 400);
    _lastPageTabIndex = index;
    _lastPageTabTapAt = now;
    if (isDoubleTap) {
      _lastPageTabTapAt = null;
      _renamePage(index);
      return;
    }
    c.selectPage(index);
  }

  Future<void> _renamePage(int index) async {
    final c = _c;
    final doc = c?.document;
    if (c == null || doc == null || index < 0 || index >= doc.pages.length) {
      return;
    }
    final textController =
        TextEditingController(text: doc.pages[index].name);
    final el = EditorL10n.of(context);
    final result = await showDialog<String>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text(el.renamePage),
        content: TextField(
          controller: textController,
          autofocus: true,
          decoration: InputDecoration(hintText: el.pageNameHint),
          onSubmitted: (v) => Navigator.pop(ctx, v),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: Text(el.cancel),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(ctx, textController.text),
            child: Text(el.ok),
          ),
        ],
      ),
    );
    if (result != null) c.renamePageAt(index, result);
    textController.dispose();
  }

  Future<void> _exportPdf() async {
    final c = _c;
    final doc = c?.document;
    if (c == null || doc == null) return;
    final el = EditorL10n.of(context);
    final path = await pickExportLocation(
      ext: 'pdf',
      suggestedName: '${baseName(c.fileName)}.pdf',
    );
    if (path == null) return;
    try {
      final bytes = await exportDocumentToPdf(doc);
      await writeBytesToFile(path, bytes);
      if (!mounted) return;
      _snack(el.exportedPdf(path));
    } catch (e) {
      if (!mounted) return;
      _snack(el.pdfExportFailed('$e'));
    }
  }

  void _snack(String message) {
    if (!mounted) return;
    ScaffoldMessenger.of(context)
      ..clearSnackBars()
      ..showSnackBar(SnackBar(content: Text(message)));
  }

  /// Editor shortcuts with both Cmd (macOS) and Ctrl (Windows/Linux) bindings.
  Map<ShortcutActivator, VoidCallback> _editorShortcutBindings(
    EditorController? Function() c,
  ) {
    final bindings = <ShortcutActivator, VoidCallback>{};

    void mod(
      LogicalKeyboardKey key,
      VoidCallback action, {
      bool shift = false,
      bool alt = false,
    }) {
      bindings[SingleActivator(key, meta: true, shift: shift, alt: alt)] =
          action;
      bindings[SingleActivator(key, control: true, shift: shift, alt: alt)] =
          action;
    }

    void redo() {
      final cur = c();
      if (cur != null && cur.canRedo) cur.redo();
    }

    mod(LogicalKeyboardKey.keyN, _newDoc);
    mod(LogicalKeyboardKey.keyO, _open);
    mod(LogicalKeyboardKey.keyW, () {
      if (_workspace.hasDocs) _closeTab(_workspace.activeIndex);
    });
    mod(LogicalKeyboardKey.keyS, () {
      if (c() != null && c()!.hasDocument) _save();
    });
    mod(LogicalKeyboardKey.keyZ, () {
      final cur = c();
      if (cur != null && cur.canUndo) cur.undo();
    });
    mod(LogicalKeyboardKey.keyZ, redo, shift: true);
    // Windows/Linux redo convention; also bind meta+Y for completeness.
    bindings[const SingleActivator(LogicalKeyboardKey.keyY, control: true)] =
        redo;
    bindings[const SingleActivator(LogicalKeyboardKey.keyY, meta: true)] = redo;
    mod(LogicalKeyboardKey.keyD, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.duplicateSelection();
    });
    mod(LogicalKeyboardKey.keyC, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.copySelection();
    });
    mod(LogicalKeyboardKey.keyV, () {
      final cur = c();
      if (cur != null && cur.hasDocument) {
        // Always try the system clipboard first (cross-instance paste).
        unawaited(cur.pasteFromSystem());
      }
    });
    mod(LogicalKeyboardKey.keyX, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.cut();
    });
    mod(LogicalKeyboardKey.keyA, () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectAll();
    });
    mod(LogicalKeyboardKey.keyA, () {
      final cur = c();
      if (cur != null) cur.clearSelection();
    }, shift: true);
    mod(LogicalKeyboardKey.keyB, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleBold();
    });
    mod(LogicalKeyboardKey.keyI, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleItalic();
    });
    mod(LogicalKeyboardKey.keyU, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleUnderline();
    });
    mod(LogicalKeyboardKey.keyE, () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectConnectors();
    });
    mod(LogicalKeyboardKey.keyI, () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectVertices();
    }, shift: true);
    bindings[const SingleActivator(LogicalKeyboardKey.tab)] = () {
      final cur = c();
      if (cur != null && cur.hasDocument) cur.selectNextShape();
    };
    bindings[const SingleActivator(LogicalKeyboardKey.tab, shift: true)] = () {
      final cur = c();
      if (cur != null && cur.hasDocument) {
        cur.selectNextShape(reverse: true);
      }
    };
    mod(LogicalKeyboardKey.keyF, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.bringSelectionToFront();
    }, shift: true);
    mod(LogicalKeyboardKey.keyB, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.sendSelectionToBack();
    }, shift: true);
    // draw.io: Cmd/Ctrl+] bring forward, Cmd/Ctrl+[ send backward
    mod(LogicalKeyboardKey.bracketRight, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.bringSelectionForward();
    });
    mod(LogicalKeyboardKey.bracketLeft, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.sendSelectionBackward();
    });
    mod(LogicalKeyboardKey.keyC, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.copyStyle();
    }, alt: true);
    mod(LogicalKeyboardKey.keyV, () {
      final cur = c();
      if (cur != null && cur.hasStyleClipboard) cur.pasteStyle();
    }, alt: true);
    mod(LogicalKeyboardKey.keyG, () {
      final cur = c();
      if (cur != null && cur.canGroup) cur.groupSelection();
    });
    mod(LogicalKeyboardKey.keyU, () {
      final cur = c();
      if (cur != null && cur.canUngroup) cur.ungroupSelection();
    }, shift: true);
    mod(LogicalKeyboardKey.keyR, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.rotateSelection90();
    });
    mod(LogicalKeyboardKey.keyR, () {
      final cur = c();
      if (cur != null && cur.hasSelection) {
        cur.rotateSelection90(clockwise: false);
      }
    }, shift: true);
    mod(LogicalKeyboardKey.keyF, _openFind);
    mod(LogicalKeyboardKey.keyH, () {
      _openFind(replace: true);
    });
    mod(LogicalKeyboardKey.keyM, () {
      if (c()?.singleSelectedId != null) _editData();
    });
    mod(LogicalKeyboardKey.keyK, () {
      if (c()?.singleSelectedId != null) _editLink();
    });
    mod(LogicalKeyboardKey.keyL, () {
      final cur = c();
      if (cur != null && cur.hasSelection) cur.toggleLock();
    });
    // Presentation / fullscreen: F5 enter, F11 toggle,
    // Cmd/Ctrl+Shift+P toggle (avoids Fn-keys on macOS laptops).
    // Escape is handled by PageCanvas so it does not steal the editor's
    // Escape (cancel drag / clear selection) outside presentation.
    bindings[const SingleActivator(LogicalKeyboardKey.f5)] =
        _enterPresentation;
    bindings[const SingleActivator(LogicalKeyboardKey.f11)] =
        _togglePresentation;
    mod(LogicalKeyboardKey.keyP, _togglePresentation, shift: true);
    return bindings;
  }

