  /// Fill gradient type + two colour stops + linear angle (draw.io Format).
  Widget _fillGradientControls(
    BuildContext context,
    EditorController controller,
  ) {
    final fill = controller.selectedFill;
    if (fill == null) return const SizedBox.shrink();
    final g = fill.hasGradient ? fill.gradient : null;
    final type = g?.type;
    final stop0 = g != null && g.stops.isNotEmpty
        ? g.stops.first.color?.value
        : fill.foreground?.value;
    final stop1 = g != null && g.stops.length > 1
        ? g.stops[1].color?.value
        : 0xFFFFFFFF;
    // Full circle — 0° and 180° are opposite directions in Visio.
    final angleDeg = g == null
        ? 0
        : ((g.angleRad * 180 / math.pi).round() % 360 + 360) % 360;

    void apply({
      VsdxGradientType? newType,
      int? color0,
      int? color1,
      double? angleRad,
    }) {
      final t = newType ?? type ?? VsdxGradientType.linear;
      final existing = g?.stops ?? const <VsdxGradientStop>[];
      List<VsdxGradientStop> stops;
      if (existing.isEmpty) {
        // Theme-bound solid fill → keep THEMEVAL on stop 0 (not a baked blue).
        final theme0 = fill.themeForegroundIndex;
        final first = color0 != null
            ? VsdxGradientStop(position: 0, color: VsdxColor(color0))
            : (stop0 != null
                ? VsdxGradientStop(position: 0, color: VsdxColor(stop0))
                : (theme0 != null
                    ? VsdxGradientStop(position: 0, themeColorIndex: theme0)
                    : const VsdxGradientStop(
                        position: 0,
                        color: VsdxColor(0xFF1E88E5),
                      )));
        final second = color1 != null
            ? VsdxGradientStop(position: 1, color: VsdxColor(color1))
            : VsdxGradientStop(
                position: 1,
                color: VsdxColor(stop1 ?? 0xFFFFFFFF),
              );
        stops = <VsdxGradientStop>[first, second];
      } else {
        stops = List<VsdxGradientStop>.from(existing);
        if (color0 != null) {
          final s0 = stops.first;
          stops[0] = VsdxGradientStop(
            position: s0.position,
            color: VsdxColor(color0),
            transparency: s0.transparency,
          );
        }
        if (color1 != null) {
          if (stops.length > 1) {
            final s1 = stops[1];
            stops[1] = VsdxGradientStop(
              position: s1.position,
              color: VsdxColor(color1),
              transparency: s1.transparency,
            );
          } else {
            stops.add(VsdxGradientStop(
              position: 1,
              color: VsdxColor(color1),
            ));
          }
        }
      }
      // Changing type clears a preserved Visio Dir so the writer emits the
      // canonical MS enum for the new type; angle-only edits keep Dir.
      final keepDir =
          newType == null || newType == g?.type ? g?.dir : null;
      controller.setFillGradient(
        VsdxGradient(
          type: t,
          angleRad: angleRad ?? g?.angleRad ?? 0,
          dir: keepDir,
          stops: stops,
        ),
      );
    }

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const SizedBox(height: 8),
        Text(EditorL10n.of(context).gradient, style: Theme.of(context).textTheme.labelMedium),
        const SizedBox(height: 4),
        Wrap(
          spacing: 6,
          children: [
            ChoiceChip(
              label: Text(EditorL10n.of(context).none),
              selected: g == null,
              onSelected: (_) => controller.setFillGradient(null),
              visualDensity: VisualDensity.compact,
            ),
            ChoiceChip(
              label: Text(EditorL10n.of(context).linear),
              selected: type == VsdxGradientType.linear,
              onSelected: (_) => apply(newType: VsdxGradientType.linear),
              visualDensity: VisualDensity.compact,
            ),
            ChoiceChip(
              label: Text(EditorL10n.of(context).radial),
              selected: type == VsdxGradientType.radial,
              onSelected: (_) => apply(newType: VsdxGradientType.radial),
              visualDensity: VisualDensity.compact,
            ),
          ],
        ),
        if (g != null) ...[
          const SizedBox(height: 6),
          Text(EditorL10n.of(context).start, style: Theme.of(context).textTheme.labelSmall),
          const SizedBox(height: 4),
          Wrap(
            spacing: 6,
            runSpacing: 6,
            children: [
              for (final argb in _swatches)
                _SwatchButton(
                  color: Color(argb),
                  selected: stop0 == argb,
                  onTap: () => apply(color0: argb),
                ),
            ],
          ),
          const SizedBox(height: 6),
          Text(EditorL10n.of(context).end, style: Theme.of(context).textTheme.labelSmall),
          const SizedBox(height: 4),
          Wrap(
            spacing: 6,
            runSpacing: 6,
            children: [
              for (final argb in _swatches)
                _SwatchButton(
                  color: Color(argb),
                  selected: stop1 == argb,
                  onTap: () => apply(color1: argb),
                ),
            ],
          ),
          if (type == VsdxGradientType.linear) ...[
            const SizedBox(height: 6),
            Wrap(
              spacing: 6,
              children: [
                for (final deg in const <int>[
                  0,
                  45,
                  90,
                  135,
                  180,
                  225,
                  270,
                  315,
                ])
                  ChoiceChip(
                    label: Text('$deg°'),
                    selected: angleDeg == deg,
                    onSelected: (_) =>
                        apply(angleRad: deg * math.pi / 180),
                    visualDensity: VisualDensity.compact,
                  ),
              ],
            ),
          ],
        ],
      ],
    );
  }

