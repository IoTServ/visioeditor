  /// Channel over which macOS hands us documents opened from Finder
  /// (double-click / "Open With") or the `open` command.
  static const MethodChannel _fileChannel = MethodChannel('visioeditor/files');

  /// Match [StencilGroup.expandAtWidth] for everyday libraries (General /
  /// Flowchart / Arrows): at this width the shapes sidebar opens by default.
  static const double _stencilsSidebarBreakpoint = 900;

  final EditorWorkspace _workspace = EditorWorkspace();
  final RecentFiles _recentFiles = RecentFiles();
  List<String> _recents = const <String>[];
  bool _dragging = false;
  bool _showStencils = false;
  /// Once the user toggles the shapes sidebar, stop re-seeding from width.
  bool _stencilsUserAdjusted = false;
  bool _showImageMaterials = false;
  bool _showThirdPartyIcons = false;
  bool _showFind = false;
  bool _findShowReplace = false;
  bool _showOutline = false;
  bool _showLayersPanel = false;
  bool _showRulers = true;
  bool _presentationMode = false;
  final CanvasCamera _camera = CanvasCamera();

  /// L1+L2 live-preview bridge for AI agents; null when disabled (default).
  AgentBridge? _agentBridge;

  /// Double-tap detection for page tabs ([ChoiceChip] swallows
  /// [GestureDetector.onDoubleTap]).
  int? _lastPageTabIndex;
  DateTime? _lastPageTabTapAt;

  /// Host of [PageCanvas]; used to map desktop file-drop global coords → page
  /// inches so images land under the cursor (drawio).
  final GlobalKey _canvasHostKey = GlobalKey();

  EditorController? get _c => _workspace.active;

  void _openFind({bool replace = false}) {
    if (_c == null || !_c!.hasDocument) return;
    setState(() {
      _showFind = true;
      if (replace) _findShowReplace = true;
    });
  }

  void _closeFind() {
    setState(() {
      _showFind = false;
      _findShowReplace = false;
    });
    _c?.clearFind();
  }

  void _enterPresentation() {
    final cur = _c;
    if (cur == null || !cur.hasDocument || _presentationMode) return;
    if (_showFind) _closeFind();
    cur.clearSelection();
    if (cur.tool != EditorTool.select) cur.setTool(EditorTool.select);
    setState(() => _presentationMode = true);
    _applyPresentationSystemUi(true);
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) cur.requestFitToWindow();
    });
  }

  void _exitPresentation() {
    if (!_presentationMode) return;
    setState(() => _presentationMode = false);
    _applyPresentationSystemUi(false);
    final cur = _c;
    if (cur != null && cur.hasDocument) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) cur.requestFitToWindow();
      });
    }
  }

  void _togglePresentation() {
    if (_presentationMode) {
      _exitPresentation();
    } else {
      _enterPresentation();
    }
  }

  void _applyPresentationSystemUi(bool presenting) {
    // Immersive system UI on phones/tablets; desktop chrome is handled by
    // hiding the Scaffold app bar / side panels.
    if (kIsWeb) return;
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
      case TargetPlatform.iOS:
        SystemChrome.setEnabledSystemUIMode(
          presenting
              ? SystemUiMode.immersiveSticky
              : SystemUiMode.edgeToEdge,
        );
      default:
        break;
    }
  }

