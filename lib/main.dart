    super.initState();
    _focus.addListener(() {
      if (!_focus.hasFocus) _commit();
    });
  }

  @override
  void didUpdateWidget(covariant _NumField old) {
    super.didUpdateWidget(old);
    // Refresh from the model unless the user is actively editing this field.
    if (!_focus.hasFocus && widget.value != old.value) {
      _c.text = _fmt(widget.value);
    }
  }

  @override
  void dispose() {
    _c.dispose();
    _focus.dispose();
    super.dispose();
  }

  void _commit() {
    final v = double.tryParse(_c.text.trim());
    if (v != null && v != widget.value) {
      widget.onSubmit(v);
    } else {
      _c.text = _fmt(widget.value);
    }
  }

  static String _fmt(double v) {
    final r = (v * 100).roundToDouble() / 100;
    return r == r.roundToDouble() ? r.toInt().toString() : '$r';
  }

  @override
  Widget build(BuildContext context) {
    return TextField(
      controller: _c,
      focusNode: _focus,
      keyboardType: const TextInputType.numberWithOptions(
          signed: true, decimal: true),
      textAlign: TextAlign.right,
      style: const TextStyle(fontSize: 13),
      decoration: InputDecoration(
        isDense: true,
        prefixText: '${widget.label} ',
        prefixStyle: TextStyle(
          fontSize: 12,
          color: Theme.of(context).colorScheme.onSurfaceVariant,
        ),
        contentPadding:
            const EdgeInsets.symmetric(horizontal: 8, vertical: 8),
        border: const OutlineInputBorder(),
      ),
      onSubmitted: (_) => _commit(),
    );
  }
}

/// Floating Find / Replace bar (draw.io Cmd+F / Cmd+H). Filters shapes by
/// text/name across all pages, cycles matches, and can replace labels.
class _FindBar extends StatefulWidget {
  const _FindBar({
    required this.controller,
    required this.showReplace,
    required this.onToggleReplace,
    required this.onClose,
  });

  final EditorController controller;
  final bool showReplace;
  final VoidCallback onToggleReplace;
  final VoidCallback onClose;

  @override
  State<_FindBar> createState() => _FindBarState();
}

class _FindBarState extends State<_FindBar> {
  final TextEditingController _text = TextEditingController();
  final TextEditingController _replace = TextEditingController();
  final FocusNode _focus = FocusNode();
  final FocusNode _replaceFocus = FocusNode();

  @override
  void initState() {
    super.initState();
    _text.text = widget.controller.findQuery;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!mounted) return;
      if (widget.showReplace) {
        _replaceFocus.requestFocus();
      } else {
        _focus.requestFocus();
      }
    });
  }

  @override
  void didUpdateWidget(covariant _FindBar oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (widget.showReplace && !oldWidget.showReplace) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) _replaceFocus.requestFocus();
      });
    }
  }

  @override
  void dispose() {
    _text.dispose();
    _replace.dispose();
    _focus.dispose();
    _replaceFocus.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    return Material(
      elevation: 4,
      borderRadius: BorderRadius.circular(8),
      color: scheme.surface,
      child: ListenableBuilder(
        listenable: widget.controller,
        builder: (context, _) {
          final count = widget.controller.findMatchCount;
          final ord = widget.controller.findCurrentOrdinal;
          final pageIdx = widget.controller.findCurrentPageIndex;
          final multiPage = widget.controller.pageCount > 1;
          final el = EditorL10n.of(context);
          final label = count == 0
              ? (widget.controller.findQuery.trim().isEmpty
                  ? ''
                  : el.noResults)
              : (multiPage && pageIdx != null)
                  ? '$ord/$count · p${pageIdx + 1}'
                  : '$ord / $count';
          return Padding(
            padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
            child: LayoutBuilder(
              builder: (context, constraints) {
                // Six IconButtons + count label need ~300px; fold options on
                // phones so the search field stays usable.
                final narrow = constraints.maxWidth < 380;
                return Column(
                  mainAxisSize: MainAxisSize.min,
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      children: [
                        const Icon(Icons.search, size: 18),
                        const SizedBox(width: 6),
                        Expanded(
                          child: CallbackShortcuts(
                            bindings: <ShortcutActivator, VoidCallback>{
                              const SingleActivator(LogicalKeyboardKey.escape):
                                  widget.onClose,
                            },
                            child: TextField(
                              controller: _text,
                              focusNode: _focus,
                              decoration: InputDecoration(
                                isDense: true,
                                hintText: el.findShapesHint,
                                border: InputBorder.none,
                              ),
                              onChanged: widget.controller.updateFind,
                              onSubmitted: (_) {
                                if (HardwareKeyboard.instance.isShiftPressed) {
                                  widget.controller.findPrevious();
                                } else {
                                  widget.controller.findNext();
                                }
                              },
                            ),
                          ),
                        ),
                        Flexible(
                          child: Text(
                            label,
                            textAlign: TextAlign.center,
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                            style: TextStyle(
                                fontSize: 12, color: scheme.onSurfaceVariant),
                          ),
                        ),
                        if (!narrow) ...[
                          IconButton(
                            onPressed: () =>
                                widget.controller.setFindMatchCase(
                              !widget.controller.findMatchCase,
                            ),
                            icon: Text(
                              'Aa',
                              style: TextStyle(
                                fontSize: 13,
                                fontWeight: FontWeight.w600,
                                color: widget.controller.findMatchCase
                                    ? scheme.primary
                                    : scheme.onSurfaceVariant,
                              ),
                            ),
                            tooltip: widget.controller.findMatchCase
                                ? el.matchCaseOn
                                : el.matchCaseOff,
                            visualDensity: VisualDensity.compact,
                          ),
                          IconButton(
                            onPressed: () =>
                                widget.controller.setFindWholeWord(
                              !widget.controller.findWholeWord,
                            ),
                            icon: Text(
                              'W',
                              style: TextStyle(
                                fontSize: 13,
                                fontWeight: FontWeight.w600,
                                color: widget.controller.findWholeWord
                                    ? scheme.primary
                                    : scheme.onSurfaceVariant,
                              ),
                            ),
                            tooltip: widget.controller.findWholeWord
                                ? el.wholeWordOn
                                : el.wholeWordOff,
                            visualDensity: VisualDensity.compact,
                          ),
                        ],
                        IconButton(
                          onPressed: count == 0
                              ? null
                              : widget.controller.findPrevious,
                          icon: const Icon(Icons.keyboard_arrow_up),
                          tooltip: el.previousShortcut,
                          visualDensity: VisualDensity.compact,
                        ),
                        IconButton(
                          onPressed:
                              count == 0 ? null : widget.controller.findNext,
                          icon: const Icon(Icons.keyboard_arrow_down),
                          tooltip: el.nextShortcut,
                          visualDensity: VisualDensity.compact,
                        ),
                        if (!narrow)
                          IconButton(
                            onPressed: widget.onToggleReplace,
                            icon: Icon(
                              widget.showReplace
                                  ? Icons.expand_less
                                  : Icons.find_replace,
                              size: 18,
                            ),
                            tooltip: widget.showReplace
                                ? el.hideReplace
                                : el.showReplaceShortcut,
                            visualDensity: VisualDensity.compact,
                          ),
                        if (narrow)
                          PopupMenuButton<String>(
                            tooltip: el.showReplaceShortcut,
                            padding: EdgeInsets.zero,
                            onSelected: (v) {
                              switch (v) {
                                case 'case':
                                  widget.controller.setFindMatchCase(
                                    !widget.controller.findMatchCase,
                                  );
                                case 'word':
                                  widget.controller.setFindWholeWord(
                                    !widget.controller.findWholeWord,
                                  );
                                case 'replace':
                                  widget.onToggleReplace();
                              }
                            },
                            itemBuilder: (context) => [
                              CheckedPopupMenuItem<String>(
                                value: 'case',
                                checked: widget.controller.findMatchCase,
                                child: Text(el.matchCaseOn),
                              ),
                              CheckedPopupMenuItem<String>(
                                value: 'word',
                                checked: widget.controller.findWholeWord,
                                child: Text(el.wholeWordOn),
                              ),
                              PopupMenuItem<String>(
                                value: 'replace',
                                child: Text(
                                  widget.showReplace
                                      ? el.hideReplace
                                      : el.showReplaceShortcut,
                                ),
                              ),
                            ],
                          ),
                        IconButton(
                          onPressed: widget.onClose,
                          icon: const Icon(Icons.close, size: 18),
                          tooltip: el.closeEsc,
                          visualDensity: VisualDensity.compact,
                        ),
                      ],
                    ),
                    if (widget.showReplace) ...[
                      const SizedBox(height: 2),
                      Row(
                        children: [
                          const SizedBox(width: 24),
                          Expanded(
                            child: TextField(
                              controller: _replace,
                              focusNode: _replaceFocus,
                              decoration: InputDecoration(
                                isDense: true,
                                hintText:
                                    EditorL10n.of(context).replaceWithHint,
                                border: InputBorder.none,
                              ),
                              onSubmitted: (_) => widget.controller
                                  .replaceFind(_replace.text),
                            ),
                          ),
                        ],
                      ),
                      Align(
                        alignment: Alignment.centerRight,
                        child: Wrap(
                          spacing: 4,
                          children: [
                            TextButton(
                              onPressed: count == 0
                                  ? null
                                  : () => widget.controller
                                      .replaceFind(_replace.text),
                              child: Text(EditorL10n.of(context).replace),
                            ),
                            TextButton(
                              onPressed:
                                  widget.controller.findQuery.trim().isEmpty
                                      ? null
                                      : () => widget.controller
                                          .replaceAllFind(_replace.text),
                              child: Text(EditorL10n.of(context).replaceAll),
                            ),
                          ],
                        ),
                      ),
                    ],
                  ],
                );
              },
            ),
          );
        },
      ),
    );
  }
}

class _SwatchButton extends StatelessWidget {
  const _SwatchButton({
    required this.color,
    required this.onTap,
    this.selected = false,
  });

  final Color color;
  final VoidCallback onTap;
  final bool selected;

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    return InkWell(
      onTap: onTap,
      borderRadius: BorderRadius.circular(4),
      child: Container(
        width: 28,
        height: 28,
        decoration: BoxDecoration(
          color: color,
