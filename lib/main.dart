Future<void> main(List<String> arguments) async {
  WidgetsFlutterBinding.ensureInitialized();
  // Hatch tiles for Visio FillPattern 2–24 (canvas + PNG share VsdxPainter).
  await PatternFillBuilder.warmUpShared();
  final settings = await AppSettings.load();
  runApp(VisioEditorApp(
    settings: settings,
    initialFilePaths: visioPathsFromArguments(arguments),
  ));
}

class VisioEditorApp extends StatelessWidget {
  const VisioEditorApp({
    required this.settings,
    this.initialFilePaths = const <String>[],
    super.key,
  });

  final AppSettings settings;
  final List<String> initialFilePaths;

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: settings,
      builder: (context, _) {
        final seed = settings.seedColor;
        return MaterialApp(
          onGenerateTitle: (ctx) => AppLocalizations.of(ctx).appTitle,
          debugShowCheckedModeBanner: false,
          themeMode: settings.themeMode,
          theme: ThemeData(
            colorSchemeSeed: seed,
            useMaterial3: true,
            brightness: Brightness.light,
          ),
          darkTheme: ThemeData(
            colorSchemeSeed: seed,
            useMaterial3: true,
            brightness: Brightness.dark,
          ),
          locale: settings.locale,
          supportedLocales: AppLocalizations.supportedLocales,
          localeResolutionCallback: (device, supported) {
            final forced = settings.locale;
            if (forced != null) return forced;
            if (device == null) return supported.first;
            for (final l in supported) {
              if (l.languageCode == device.languageCode) return l;
            }
            return supported.first;
          },
          localizationsDelegates: const [
            AppLocalizations.delegate,
            GlobalMaterialLocalizations.delegate,
            GlobalWidgetsLocalizations.delegate,
            GlobalCupertinoLocalizations.delegate,
          ],
          home: EditorHomePage(
            settings: settings,
            initialFilePaths: initialFilePaths,
          ),
        );
      },
    );
  }
}

