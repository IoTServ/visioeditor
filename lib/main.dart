/// Cached geometry for a stencil thumbnail (shape build is relatively expensive
/// when hundreds of tiles are in the palette).
class _ThumbGeom {
  _ThumbGeom(
    this.width,
    this.height,
    this.paths, {
    this.label,
  });

  final double width;
  final double height;
  final List<
      ({
        Path path,
        bool fill,
        bool line,
        Color fillColor,
        Color strokeColor,
      })> paths;

  /// Shape text used when the geometry has no fill/line (e.g. the Text stencil).
  final String? label;

  bool get hasVisiblePaths => paths.any((p) => p.fill || p.line);
}

/// Paints a stencil's real geometry into a thumbnail box. Builds the shape once
/// (pin irrelevant), then maps its shape-local coordinates (origin bottom-left,
/// Y-up, inches) into the box (origin top-left, Y-down) with a Y-flip so the
/// preview matches what drops on the canvas.
///
/// Records a [ui.Picture] per (stencil, colours, size) so scrolling the shapes
/// panel only blits pictures instead of rebuilding paths every frame.
class _StencilThumbPainter extends CustomPainter {
  _StencilThumbPainter(this.stencil);

  final Stencil stencil;

  static final Map<Stencil, _ThumbGeom> _geomCache = <Stencil, _ThumbGeom>{};
  static final Map<(Stencil, int, int), ui.Picture> _pictureCache =
      <(Stencil, int, int), ui.Picture>{};

  static Color _flutterColor(VsdxColor? c, {required Color fallback}) {
    if (c == null) return fallback;
    return Color(c.value);
  }

  _ThumbGeom _geom() {
    final hit = _geomCache[stencil];
    if (hit != null) return hit;
    final shape = stencil.build(0, 0, 0);
    final w = shape.width;
    final h = shape.height;
    final paths = <({Path path, bool fill, bool line, Color fillColor, Color strokeColor})>[];
    if (w > 0 && h > 0) {
      _collectThumbPaths(shape, paths, root: true);
    }
    final label = shape.text?.trim();
    return _geomCache[stencil] = _ThumbGeom(
      w,
      h,
      paths,
      label: (label != null && label.isNotEmpty) ? label : null,
    );
  }

  void _collectThumbPaths(
    VsdxShape shape,
    List<
            ({
              Path path,
              bool fill,
              bool line,
              Color fillColor,
              Color strokeColor,
            })>
        out, {
    double ox = 0,
    double oy = 0,
    bool root = false,
  }) {
    final w = shape.width;
    final h = shape.height;
    final fillColor = shape.fill.hasFill
        ? _flutterColor(shape.fill.foreground, fallback: const Color(0xFFDAE8FC))
        : const Color(0x00000000);
    final strokeColor = shape.line.hasLine
        ? _flutterColor(shape.line.color, fallback: const Color(0xFF6C8EBF))
        : const Color(0x00000000);
    // Root: paint in shape-local inches (0…W, 0…H). Children: offset by Pin
    // relative to the parent's bottom-left (LocPin defaults to centre).
    final originX = root ? 0.0 : ox + shape.pinX - w / 2;
    final originY = root ? 0.0 : oy + shape.pinY - h / 2;
    if (w > 0 && h > 0) {
      for (final g in shape.geometries) {
        if (g.noShow) continue;
        final raw = buildPath(g, widthInches: w, heightInches: h);
        final shifted = root ? raw : raw.shift(Offset(originX, originY));
        out.add((
          path: shifted,
          fill: !g.noFill && shape.fill.hasFill,
          line: !g.noLine && shape.line.hasLine,
          fillColor: fillColor,
          strokeColor: strokeColor,
        ));
      }
    }
    for (final child in shape.children) {
      _collectThumbPaths(child, out, ox: originX, oy: originY);
    }
  }

  ui.Picture _picture(Size size) {
    final key = (stencil, size.width.round(), size.height.round());
    final hit = _pictureCache[key];
    if (hit != null) return hit;
    final recorder = ui.PictureRecorder();
    final canvas = Canvas(recorder);
    final geom = _geom();
    final w = geom.width;
    final h = geom.height;
    if (w > 0 && h > 0 && geom.hasVisiblePaths) {
      const pad = 5.0;
      final s = math.min(
        (size.width - 2 * pad) / w,
        (size.height - 2 * pad) / h,
      );
      if (s > 0) {
        final dx = (size.width - w * s) / 2;
        final dy = (size.height - h * s) / 2;
        canvas.save();
        canvas.translate(dx, size.height - dy);
        canvas.scale(s, -s);
        for (final p in geom.paths) {
          if (p.fill) {
            canvas.drawPath(
              p.path,
              Paint()
                ..color = p.fillColor
                ..style = PaintingStyle.fill,
            );
          }
          if (p.line) {
            canvas.drawPath(
              p.path,
              Paint()
                ..color = p.strokeColor
                ..style = PaintingStyle.stroke
                ..strokeWidth = 1.2 / s
                ..strokeJoin = StrokeJoin.round
                ..strokeCap = StrokeCap.round,
            );
          }
        }
        canvas.restore();
      }
    } else if (geom.label != null) {
      // Text-only stencils (fill/line off): show the label as the icon.
      final tp = TextPainter(
        text: TextSpan(
          text: geom.label,
          style: const TextStyle(
            color: Color(0xFF374151),
            fontSize: 12,
            fontWeight: FontWeight.w700,
            letterSpacing: 0.2,
            height: 1.05,
          ),
        ),
        textAlign: TextAlign.center,
        textDirection: TextDirection.ltr,
        maxLines: 2,
        ellipsis: '…',
      )..layout(maxWidth: math.max(8.0, size.width - 4));
      tp.paint(
        canvas,
        Offset(
          (size.width - tp.width) / 2,
          (size.height - tp.height) / 2,
        ),
      );
    }
    return _pictureCache[key] = recorder.endRecording();
  }

  @override
  void paint(Canvas canvas, Size size) {
    if (size.isEmpty) return;
    canvas.drawPicture(_picture(size));
  }

  @override
  bool shouldRepaint(covariant _StencilThumbPainter old) =>
      old.stencil != stencil;
}

